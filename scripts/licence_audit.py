"""Licence audit of the API's declared dependencies, read from installed package metadata.

Usage: python scripts/licence_audit.py > docs/LICENSES.md   (run after `pip install -e apps/api[pdf,llm]`)

Copyleft is flagged rather than refused: the repo is AGPL-3.0 itself, so GPL/AGPL deps are
compatible, but a closed-source deployment would need them replaced. Unknown licences are
reported as UNKNOWN so a human reads them before release.
"""
import importlib.metadata as md
import re
import sys
import tomllib
from pathlib import Path

PYPROJECT = Path(__file__).resolve().parents[1] / "apps" / "api" / "pyproject.toml"
PERMISSIVE = ("MIT", "BSD", "Apache", "ISC", "PSF", "Python-2.0", "Unlicense", "0BSD", "MPL")
COPYLEFT = ("GPL", "LGPL", "AGPL")


def declared(extras: tuple[str, ...]) -> list[str]:
    proj = tomllib.loads(PYPROJECT.read_text())["project"]
    specs = list(proj["dependencies"])
    for extra in extras:
        specs += proj.get("optional-dependencies", {}).get(extra, [])
    return sorted({re.split(r"[\[<>=!~ ]", s, maxsplit=1)[0] for s in specs})


def classify(license_text: str, classifiers: list[str]) -> str:
    text = license_text or " ".join(c.split("::")[-1].strip() for c in classifiers if c.startswith("License ::"))
    if not text:
        return "UNKNOWN"
    if any(tag in text for tag in COPYLEFT):
        return "COPYLEFT"
    if any(tag in text for tag in PERMISSIVE):
        return "PERMISSIVE"
    return "UNKNOWN"


def main() -> int:
    rows, flagged = [], 0
    for name in declared(("pdf", "llm", "dev")):
        try:
            meta = md.metadata(name)
        except md.PackageNotFoundError:
            rows.append(f"| {name} | not installed | NOT AUDITED |")
            continue
        lic = meta.get("License-Expression") or meta.get("License") or "(none)"
        kind = classify(lic if lic != "(none)" else "", meta.get_all("Classifier") or [])
        flagged += kind != "PERMISSIVE"
        rows.append(f"| {name} | {lic.splitlines()[0][:60]} | {kind} |")
    print("# Dependency licences\n\nGenerated by `scripts/licence_audit.py`. Copyleft and unknown rows need a human read before any closed-source release.\n")
    print("| Package | Licence | Class |\n|---|---|---|")
    print("\n".join(rows))
    return 0


if __name__ == "__main__":
    sys.exit(main())
